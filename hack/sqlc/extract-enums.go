// extract-enums moves the enum types that sqlc.yaml overrides to pkg/enums out
// of the generated models.go and into pkg/enums/enums.gen.go, so each enum has
// exactly one Go type shared by the repository, API and client layers. It then
// generates the API-facing subsets of those enums declared in pkg/enums/subsets.yaml.
//
// Run from the repo root after sqlc generation:
//
//	go run ./hack/sqlc/extract-enums.go
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/printer"
	"go/token"
	"log"
	"os"
	"sort"
	"strings"

	"gopkg.in/yaml.v3"
)

const (
	sqlcConfigPath = "pkg/repository/sqlcv1/sqlc.yaml"
	modelsPath     = "pkg/repository/sqlcv1/models.go"
	outPath        = "pkg/enums/enums.gen.go"
	subsetsPath    = "pkg/enums/subsets.yaml"
	subsetsOutPath = "pkg/enums/subsets.gen.go"
	enumsImport    = "github.com/hatchet-dev/hatchet/pkg/enums"
)

type sqlcConfig struct {
	SQL []struct {
		Gen struct {
			Go struct {
				Overrides []struct {
					GoType struct {
						Import string `yaml:"import"`
						Type   string `yaml:"type"`
					} `yaml:"go_type"`
				} `yaml:"overrides"`
			} `yaml:"go"`
		} `yaml:"gen"`
	} `yaml:"sql"`
}

func main() {
	extract()
	generateSubsets()
}

func extract() {
	raw, err := os.ReadFile(sqlcConfigPath)
	if err != nil {
		log.Fatal(err)
	}

	var cfg sqlcConfig
	if err := yaml.Unmarshal(raw, &cfg); err != nil {
		log.Fatal(err)
	}

	names := map[string]bool{}
	for _, s := range cfg.SQL {
		for _, o := range s.Gen.Go.Overrides {
			if o.GoType.Import == enumsImport {
				names[strings.TrimPrefix(o.GoType.Type, "Null")] = true
			}
		}
	}

	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, modelsPath, nil, parser.ParseComments)
	if err != nil {
		log.Fatal(err)
	}

	var moved, dropped, kept []ast.Decl
	found := map[string]bool{}

	for _, decl := range file.Decls {
		if name, ok := enumDeclOwner(decl); ok && names[name] {
			found[name] = true
			// sqlc.yaml maps nullable columns to *T, so the Null wrapper would be dead code
			if isNullDecl(decl) {
				dropped = append(dropped, decl)
			} else {
				moved = append(moved, decl)
			}
			continue
		}
		kept = append(kept, decl)
	}

	// models.go was already extracted and sqlc has not been rerun since
	if len(found) == 0 {
		return
	}

	var missing []string
	for n := range names {
		if !found[n] {
			missing = append(missing, n)
		}
	}
	sort.Strings(missing)
	if len(missing) > 0 {
		log.Fatalf("overridden enums not found in %s (does its db_type match the schema?): %s", modelsPath, strings.Join(missing, ", "))
	}

	allComments := file.Comments
	file.Decls = kept
	file.Comments = dropComments(allComments, append(moved, dropped...))
	dropUnusedImports(file, "driver", "fmt")

	var modelsBuf bytes.Buffer
	if err := printer.Fprint(&modelsBuf, fset, file); err != nil {
		log.Fatal(err)
	}
	writeFormatted(modelsPath, modelsBuf.Bytes())

	var body bytes.Buffer
	for _, d := range moved {
		if err := printer.Fprint(&body, fset, &printer.CommentedNode{Node: d, Comments: allComments}); err != nil {
			log.Fatal(err)
		}
		body.WriteString("\n\n")
	}

	var out bytes.Buffer
	out.WriteString("// Code generated by hack/sqlc/extract-enums.go from sqlc output. DO NOT EDIT.\n\n")
	out.WriteString("package enums\n\nimport (\n")
	if bytes.Contains(body.Bytes(), []byte("driver.")) {
		out.WriteString("\t\"database/sql/driver\"\n")
	}
	out.WriteString("\t\"fmt\"\n)\n\n")
	out.Write(body.Bytes())

	if err := os.MkdirAll("pkg/enums", 0o755); err != nil {
		log.Fatal(err)
	}
	writeFormatted(outPath, out.Bytes())
}

// enumDeclOwner returns the enum type name a sqlc-generated decl belongs to:
// the enum type itself, its Null wrapper, its const block, or a method on either.
func enumDeclOwner(decl ast.Decl) (string, bool) {
	switch d := decl.(type) {
	case *ast.GenDecl:
		if d.Tok == token.TYPE && len(d.Specs) == 1 {
			ts := d.Specs[0].(*ast.TypeSpec)
			return strings.TrimPrefix(ts.Name.Name, "Null"), true
		}
		if d.Tok == token.CONST {
			for _, s := range d.Specs {
				vs := s.(*ast.ValueSpec)
				if id, ok := vs.Type.(*ast.Ident); ok {
					return id.Name, true
				}
			}
		}
	case *ast.FuncDecl:
		if d.Recv == nil || len(d.Recv.List) != 1 {
			if strings.HasPrefix(d.Name.Name, "All") && strings.HasSuffix(d.Name.Name, "Values") {
				return strings.TrimSuffix(strings.TrimPrefix(d.Name.Name, "All"), "Values"), true
			}
			return "", false
		}
		t := d.Recv.List[0].Type
		if star, ok := t.(*ast.StarExpr); ok {
			t = star.X
		}
		if id, ok := t.(*ast.Ident); ok {
			return strings.TrimPrefix(id.Name, "Null"), true
		}
	}
	return "", false
}

func isNullDecl(decl ast.Decl) bool {
	switch d := decl.(type) {
	case *ast.GenDecl:
		if d.Tok == token.TYPE && len(d.Specs) == 1 {
			return strings.HasPrefix(d.Specs[0].(*ast.TypeSpec).Name.Name, "Null")
		}
	case *ast.FuncDecl:
		if d.Recv != nil && len(d.Recv.List) == 1 {
			t := d.Recv.List[0].Type
			if star, ok := t.(*ast.StarExpr); ok {
				t = star.X
			}
			if id, ok := t.(*ast.Ident); ok {
				return strings.HasPrefix(id.Name, "Null")
			}
		}
	}
	return false
}

// dropComments removes the comments that belong to moved decls, including
// doc comments, which sit before the decl's own position.
func dropComments(all []*ast.CommentGroup, moved []ast.Decl) []*ast.CommentGroup {
	var out []*ast.CommentGroup
	for _, c := range all {
		inMoved := false
		for _, d := range moved {
			if c.Pos() >= declStart(d) && c.End() <= d.End() {
				inMoved = true
				break
			}
		}
		if !inMoved {
			out = append(out, c)
		}
	}
	return out
}

func declStart(d ast.Decl) token.Pos {
	switch d := d.(type) {
	case *ast.FuncDecl:
		if d.Doc != nil {
			return d.Doc.Pos()
		}
	case *ast.GenDecl:
		if d.Doc != nil {
			return d.Doc.Pos()
		}
	}
	return d.Pos()
}

func dropUnusedImports(file *ast.File, pkgNames ...string) {
	used := map[string]bool{}
	ast.Inspect(file, func(n ast.Node) bool {
		if sel, ok := n.(*ast.SelectorExpr); ok {
			if id, ok := sel.X.(*ast.Ident); ok {
				used[id.Name] = true
			}
		}
		return true
	})

	drop := map[string]bool{}
	for _, p := range pkgNames {
		if !used[p] {
			drop[p] = true
		}
	}

	for _, decl := range file.Decls {
		gd, ok := decl.(*ast.GenDecl)
		if !ok || gd.Tok != token.IMPORT {
			continue
		}
		var specs []ast.Spec
		for _, s := range gd.Specs {
			path := strings.Trim(s.(*ast.ImportSpec).Path.Value, `"`)
			if drop[path[strings.LastIndex(path, "/")+1:]] {
				continue
			}
			specs = append(specs, s)
		}
		gd.Specs = specs
	}
}

func writeFormatted(path string, src []byte) {
	formatted, err := format.Source(src)
	if err != nil {
		log.Fatalf("formatting %s: %v", path, err)
	}
	if err := os.WriteFile(path, formatted, 0644); err != nil { // nolint:gosec
		log.Fatal(err)
	}
}

type subset struct {
	From    string   `yaml:"from"`
	Exclude []string `yaml:"exclude"`
}

type enumValue struct {
	name  string
	value string
}

// generateSubsets writes a distinct type per subset so code holding a database value has to narrow it before it reaches the API.
func generateSubsets() {
	raw, err := os.ReadFile(subsetsPath)
	if err != nil {
		log.Fatal(err)
	}

	var subsets map[string]subset
	if err := yaml.Unmarshal(raw, &subsets); err != nil {
		log.Fatal(err)
	}

	source, err := parser.ParseFile(token.NewFileSet(), outPath, nil, 0)
	if err != nil {
		log.Fatal(err)
	}

	names := make([]string, 0, len(subsets))
	for n := range subsets {
		names = append(names, n)
	}
	sort.Strings(names)

	var out bytes.Buffer
	out.WriteString("// Code generated by hack/sqlc/extract-enums.go from subsets.yaml. DO NOT EDIT.\n\npackage enums\n\n")

	for _, name := range names {
		sub := subsets[name]

		all := enumValues(source, sub.From)
		if len(all) == 0 {
			log.Fatalf("subset %s: enum %s not found in %s", name, sub.From, outPath)
		}

		excluded := map[string]bool{}
		for _, e := range sub.Exclude {
			excluded[e] = true
		}

		var kept []string
		for _, v := range all {
			if excluded[v.value] {
				delete(excluded, v.value)
				continue
			}
			kept = append(kept, v.value)
		}

		if len(excluded) > 0 {
			var stale []string
			for e := range excluded {
				stale = append(stale, e)
			}
			sort.Strings(stale)
			log.Fatalf("subset %s excludes values not in %s: %s", name, sub.From, strings.Join(stale, ", "))
		}

		writeSubset(&out, name, sub.From, kept)
	}

	writeFormatted(subsetsOutPath, out.Bytes())
}

func enumValues(file *ast.File, typeName string) []enumValue {
	var vals []enumValue
	for _, decl := range file.Decls {
		gd, ok := decl.(*ast.GenDecl)
		if !ok || gd.Tok != token.CONST {
			continue
		}
		for _, s := range gd.Specs {
			vs := s.(*ast.ValueSpec)
			id, ok := vs.Type.(*ast.Ident)
			if !ok || id.Name != typeName || len(vs.Values) != 1 {
				continue
			}
			lit, ok := vs.Values[0].(*ast.BasicLit)
			if !ok {
				continue
			}
			vals = append(vals, enumValue{name: vs.Names[0].Name, value: strings.Trim(lit.Value, `"`)})
		}
	}
	return vals
}

func writeSubset(out *bytes.Buffer, name, from string, values []string) {
	fmt.Fprintf(out, "// %s is the subset of %s exposed outside the database; convert with Narrow.\n", name, from)
	fmt.Fprintf(out, "type %s string\n\nconst (\n", name)
	for _, v := range values {
		fmt.Fprintf(out, "\t%s%s %s = %q\n", name, v, name, v)
	}
	out.WriteString(")\n\n")

	fmt.Fprintf(out, "func (e %s) Valid() bool {\n\tswitch e {\n\tcase ", name)
	for i, v := range values {
		if i > 0 {
			out.WriteString(",\n\t\t")
		}
		fmt.Fprintf(out, "%s%s", name, v)
	}
	out.WriteString(":\n\t\treturn true\n\t}\n\treturn false\n}\n\n")

	fmt.Fprintf(out, "func All%sValues() []%s {\n\treturn []%s{\n", name, name, name)
	for _, v := range values {
		fmt.Fprintf(out, "\t\t%s%s,\n", name, v)
	}
	out.WriteString("\t}\n}\n\n")
}
