// extract-enums moves the enum types that sqlc.yaml overrides to pkg/enums out
// of the generated models.go and into pkg/enums/enums.gen.go, so each enum has
// exactly one Go type shared by the repository, API and client layers.
//
// Run from the repo root after sqlc generation:
//
//	go run ./hack/sqlc/extract-enums.go
package main

import (
	"bytes"
	"go/ast"
	"go/format"
	"go/parser"
	"go/printer"
	"go/token"
	"log"
	"os"
	"sort"
	"strings"

	"gopkg.in/yaml.v3"
)

const (
	sqlcConfigPath = "pkg/repository/sqlcv1/sqlc.yaml"
	modelsPath     = "pkg/repository/sqlcv1/models.go"
	outPath        = "pkg/enums/enums.gen.go"
	enumsImport    = "github.com/hatchet-dev/hatchet/pkg/enums"
)

type sqlcConfig struct {
	SQL []struct {
		Gen struct {
			Go struct {
				Overrides []struct {
					GoType struct {
						Import string `yaml:"import"`
						Type   string `yaml:"type"`
					} `yaml:"go_type"`
				} `yaml:"overrides"`
			} `yaml:"go"`
		} `yaml:"gen"`
	} `yaml:"sql"`
}

func main() {
	raw, err := os.ReadFile(sqlcConfigPath)
	if err != nil {
		log.Fatal(err)
	}

	var cfg sqlcConfig
	if err := yaml.Unmarshal(raw, &cfg); err != nil {
		log.Fatal(err)
	}

	names := map[string]bool{}
	for _, s := range cfg.SQL {
		for _, o := range s.Gen.Go.Overrides {
			if o.GoType.Import == enumsImport {
				names[strings.TrimPrefix(o.GoType.Type, "Null")] = true
			}
		}
	}

	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, modelsPath, nil, parser.ParseComments)
	if err != nil {
		log.Fatal(err)
	}

	var moved []ast.Decl
	var kept []ast.Decl
	found := map[string]bool{}

	for _, decl := range file.Decls {
		if name, ok := enumDeclOwner(decl); ok && names[name] {
			moved = append(moved, decl)
			found[name] = true
			continue
		}
		kept = append(kept, decl)
	}

	// models.go was already extracted and sqlc has not been rerun since
	if len(found) == 0 {
		return
	}

	var missing []string
	for n := range names {
		if !found[n] {
			missing = append(missing, n)
		}
	}
	sort.Strings(missing)
	if len(missing) > 0 {
		log.Fatalf("overridden enums not found in %s (does its db_type match the schema?): %s", modelsPath, strings.Join(missing, ", "))
	}

	allComments := file.Comments
	file.Decls = kept
	file.Comments = dropComments(allComments, moved)
	dropUnusedImports(file, "driver", "fmt")

	var modelsBuf bytes.Buffer
	if err := printer.Fprint(&modelsBuf, fset, file); err != nil {
		log.Fatal(err)
	}
	writeFormatted(modelsPath, modelsBuf.Bytes())

	var out bytes.Buffer
	out.WriteString("// Code generated by hack/sqlc/extract-enums.go from sqlc output. DO NOT EDIT.\n\n")
	out.WriteString("package enums\n\nimport (\n\t\"database/sql/driver\"\n\t\"fmt\"\n)\n\n")
	for _, d := range moved {
		var b bytes.Buffer
		if err := printer.Fprint(&b, fset, &printer.CommentedNode{Node: d, Comments: allComments}); err != nil {
			log.Fatal(err)
		}
		out.Write(b.Bytes())
		out.WriteString("\n\n")
	}

	if err := os.MkdirAll("pkg/enums", 0o755); err != nil {
		log.Fatal(err)
	}
	writeFormatted(outPath, out.Bytes())
}

// enumDeclOwner returns the enum type name a sqlc-generated decl belongs to:
// the enum type itself, its Null wrapper, its const block, or a method on either.
func enumDeclOwner(decl ast.Decl) (string, bool) {
	switch d := decl.(type) {
	case *ast.GenDecl:
		if d.Tok == token.TYPE && len(d.Specs) == 1 {
			ts := d.Specs[0].(*ast.TypeSpec)
			return strings.TrimPrefix(ts.Name.Name, "Null"), true
		}
		if d.Tok == token.CONST {
			for _, s := range d.Specs {
				vs := s.(*ast.ValueSpec)
				if id, ok := vs.Type.(*ast.Ident); ok {
					return id.Name, true
				}
			}
		}
	case *ast.FuncDecl:
		if d.Recv == nil || len(d.Recv.List) != 1 {
			if strings.HasPrefix(d.Name.Name, "All") && strings.HasSuffix(d.Name.Name, "Values") {
				return strings.TrimSuffix(strings.TrimPrefix(d.Name.Name, "All"), "Values"), true
			}
			return "", false
		}
		t := d.Recv.List[0].Type
		if star, ok := t.(*ast.StarExpr); ok {
			t = star.X
		}
		if id, ok := t.(*ast.Ident); ok {
			return strings.TrimPrefix(id.Name, "Null"), true
		}
	}
	return "", false
}

// dropComments removes the comments that belong to moved decls, including
// doc comments, which sit before the decl's own position.
func dropComments(all []*ast.CommentGroup, moved []ast.Decl) []*ast.CommentGroup {
	var out []*ast.CommentGroup
	for _, c := range all {
		inMoved := false
		for _, d := range moved {
			if c.Pos() >= declStart(d) && c.End() <= d.End() {
				inMoved = true
				break
			}
		}
		if !inMoved {
			out = append(out, c)
		}
	}
	return out
}

func declStart(d ast.Decl) token.Pos {
	switch d := d.(type) {
	case *ast.FuncDecl:
		if d.Doc != nil {
			return d.Doc.Pos()
		}
	case *ast.GenDecl:
		if d.Doc != nil {
			return d.Doc.Pos()
		}
	}
	return d.Pos()
}

func dropUnusedImports(file *ast.File, pkgNames ...string) {
	used := map[string]bool{}
	ast.Inspect(file, func(n ast.Node) bool {
		if sel, ok := n.(*ast.SelectorExpr); ok {
			if id, ok := sel.X.(*ast.Ident); ok {
				used[id.Name] = true
			}
		}
		return true
	})

	drop := map[string]bool{}
	for _, p := range pkgNames {
		if !used[p] {
			drop[p] = true
		}
	}

	for _, decl := range file.Decls {
		gd, ok := decl.(*ast.GenDecl)
		if !ok || gd.Tok != token.IMPORT {
			continue
		}
		var specs []ast.Spec
		for _, s := range gd.Specs {
			path := strings.Trim(s.(*ast.ImportSpec).Path.Value, `"`)
			if drop[path[strings.LastIndex(path, "/")+1:]] {
				continue
			}
			specs = append(specs, s)
		}
		gd.Specs = specs
	}
}

func writeFormatted(path string, src []byte) {
	formatted, err := format.Source(src)
	if err != nil {
		log.Fatalf("formatting %s: %v", path, err)
	}
	if err := os.WriteFile(path, formatted, 0644); err != nil { // nolint:gosec
		log.Fatal(err)
	}
}
